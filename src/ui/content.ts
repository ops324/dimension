/**
 * ギャラリー展示のメタ情報と解説(プラン8節「各展示に『解説』トグル」)。
 *
 * Phase 15 で解説を**二層**にした(ゲームのコーデックス/図鑑の構成):
 *
 *   やさしい層(codex) … 専門用語ゼロで読める。フック → 導入 → たとえ話 →
 *                        観察ポイント → クエスト(操作ガイド)→ 図鑑データ。
 *                        「わかる」より先に「見たくなる」を作るのが役目。
 *   深い層(explanation)… 従来の科学解説そのまま。DEEP DIVE として折りたたみ、
 *                        潜りたい人だけが潜る。数学的な正確さは一切妥協しない。
 *
 * `explanation` は装飾 HTML(`<p>` / `<em>` / `<sup>`)。KaTeX は使わない ──
 * 数式は本文の呼吸を壊さない範囲で、語りの中に埋め込む方針。
 *
 * codex の文体規律:
 *   - 一文目で必ず「えっ」を作る(hook は疑問か逆説)
 *   - たとえ話は 1 展示に 1 本だけ。混ぜない
 *   - クエストは**実在するパネル操作**だけを指す(ラベル名は panel と一致させる)
 *   - 数字は本物を使う(1,200 本・1,024 個 ── 概数でごまかさない)
 */

/** クエスト = パネル操作への誘い。title は命令形、body は「何が見られるか」の予告 */
export interface CodexQuest {
  readonly title: string;
  readonly body: string;
}

/** 図鑑データの 1 行。label は欧文モノ、value は短い日本語 */
export interface CodexStat {
  readonly label: string;
  readonly value: string;
}

/** やさしい層の全体。Drawer.ts がこの構造からコーデックス DOM を組む */
export interface ExhibitCodex {
  /** 一行のフック(ドロワー冒頭の大きな文字) */
  readonly hook: string;
  /** 導入 2〜3 文。専門用語ゼロ */
  readonly intro: string;
  /** たとえ話カードの見出しと本文 */
  readonly metaphorTitle: string;
  readonly metaphor: string;
  /** 「いま見えているもの」── 画面の観察ポイント */
  readonly observe: readonly string[];
  /** TRY THIS ── パネル操作のクエスト */
  readonly quests: readonly CodexQuest[];
  /** 図鑑データ(2 列グリッド) */
  readonly stats: readonly CodexStat[];
}

export interface ExhibitInfo {
  readonly id: string;
  /** タブとヘッダの英字ディスプレイ */
  readonly en: string;
  /** 英字に添える日本語 */
  readonly jp: string;
  /** 一行の惹句(ヘッダに出る) */
  readonly tagline: string;
  /** やさしい層(Phase 15) */
  readonly codex: ExhibitCodex;
  /** 深い層 ── 「解説」ドロワーの DEEP DIVE 本文(装飾 HTML) */
  readonly explanation: string;
}

