/**
 * ギャラリー展示のメタ情報と科学解説(プラン8節「各展示に『解説』トグル」)。
 *
 * `explanation` は装飾 HTML(`<p>` / `<em>` / `<sup>`)。KaTeX は使わない ──
 * 数式は本文の呼吸を壊さない範囲で、語りの中に埋め込む方針。
 *
 * 文体は章テキストと同じ register を保つ: 平易な語彙・短い断定・比喩は一本。
 * ただし数学的な内容は一切妥協しない(ファイバー束・平坦性・族の分類は正確に)。
 */
export interface ExhibitInfo {
  readonly id: string;
  /** タブとヘッダの英字ディスプレイ */
  readonly en: string;
  /** 英字に添える日本語 */
  readonly jp: string;
  /** 一行の惹句(ヘッダに出る) */
  readonly tagline: string;
  /** 「解説」ドロワーの本文(装飾 HTML) */
  readonly explanation: string;
}

